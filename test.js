let pass = 0, fail = 0;

function expect(name, text, family, shouldHit) {
  const hits = fwScanText(text).filter(h => h.family === family);
  const got = hits.length > 0;
  if (got === shouldHit) {
    pass++;
    console.log('PASS  ' + name);
  } else {
    fail++;
    console.log('FAIL  ' + name + '  (expected ' + (shouldHit ? 'hit' : 'clean') + ', got ' + (got ? 'hit' : 'clean') + ')');
    if (hits.length) console.log('      match: ' + hits[0].match);
  }
}

function expectOrigin(name, text, labId, countryNeedle) {
  const hits = fwScanText(text).filter(h => h.origin && h.origin.labId === labId);
  if (!hits.length) {
    fail++;
    console.log('FAIL  ' + name + '  (no origin for ' + labId + ')');
    return;
  }
  const country = hits[0].origin.country || '';
  if (countryNeedle && country.indexOf(countryNeedle) === -1) {
    fail++;
    console.log('FAIL  ' + name + '  (country "' + country + '" missing "' + countryNeedle + '")');
    return;
  }
  pass++;
  console.log('PASS  ' + name);
}

